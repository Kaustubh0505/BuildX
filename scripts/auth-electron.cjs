const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const os = require('node:os')
const path = require('node:path')
const { _electron: electron } = require('playwright-core')
const { createDesktopFixture } = require('./cloud-fixture.cjs')
const { createProjectStore } = require('../electron/project-store.cjs')
const { PASSWORD } = require('../server/tests/support.cjs')

async function main() {
  const fixture = await createDesktopFixture()
  const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'buildx-auth-ui-'))
  const local = createProjectStore({ directory: path.join(directory, 'projects') })
  const legacy = await local.create({ title: 'Legacy idea', problem: 'Import my existing blueprint.' })
  const environment = { ...process.env, ELECTRON_RENDERER_URL: '', BUILDX_API_URL: fixture.url, BUILDX_E2E: '1', BUILDX_E2E_USER_DATA: directory }
  delete environment.ELECTRON_RUN_AS_NODE
  let app
  const pageErrors = []
  async function launch() {
    app = await electron.launch({ args: ['.'], cwd: path.join(__dirname, '..'), env: environment })
    const page = await app.firstWindow()
    page.on('pageerror', (error) => pageErrors.push(error.message))
    return page
  }
  async function signin(page, email, password = 'x') {
    await page.locator('#auth-email').fill(email)
    await page.locator('#auth-password').fill(password)
    await page.locator('button[type="submit"]').click()
  }
  try {
    let page = await launch()
    await page.getByRole('heading', { name: 'Welcome to BuildX.' }).waitFor()
    if (process.env.BUILDX_SCREENSHOT_DIR) {
      await fs.mkdir(process.env.BUILDX_SCREENSHOT_DIR, { recursive: true })
      await page.screenshot({ path: path.join(process.env.BUILDX_SCREENSHOT_DIR, 'buildx-login.png') })
    }
    await page.getByRole('button', { name: 'Sign up', exact: true }).click()
    await page.getByRole('button', { name: 'Create account', exact: true }).click()
    await page.getByText('Enter a name of 1–100 characters.').waitFor()
    assert.equal(await page.locator('#auth-name').evaluate((node) => node === document.activeElement), true)
    await page.locator('#auth-name').fill('Ada Lovelace')
    await page.locator('#auth-email').fill(' ADA@EXAMPLE.COM ')
    await page.locator('#auth-password').fill('')
    await page.getByRole('button', { name: 'Create account', exact: true }).click()
    await page.getByText('Enter your password.', { exact: true }).waitFor()
    await page.locator('#auth-password').fill('x')
    await page.getByRole('button', { name: 'Show password', exact: true }).click()
    assert.equal(await page.locator('#auth-password').getAttribute('type'), 'text')
    await page.getByRole('button', { name: 'Hide password', exact: true }).click()
    await page.getByRole('button', { name: 'Create account', exact: true }).click()
    await page.getByRole('button', { name: 'Creating account…' }).waitFor()
    assert.equal(await page.locator('#auth-email').isDisabled(), true)
    await page.getByText('Account created. Sign in to continue.').waitFor()
    assert.equal(await page.locator('#auth-password').inputValue(), '')
    await signin(page, 'ada@example.com', 'an incorrect password')
    await page.getByText('Email or password is incorrect.').waitFor()
    await signin(page, 'ada@example.com')
    await page.getByRole('heading', { name: 'Start with a clear plan.' }).waitFor()
    await page.getByText('Ada Lovelace', { exact: true }).waitFor()
    assert.equal(await page.getByRole('button', { name: 'Import existing projects' }).count(), 0)
    await page.getByRole('button', { name: 'Open Legacy idea' }).waitFor()
    assert.equal((await local.get(legacy.id)).title, 'Legacy idea')
    await page.getByRole('button', { name: 'Open Legacy idea' }).click()
    await page.locator('#project-problem').fill('An offline draft to preserve.')
    const port = fixture.http.address().port
    await new Promise((resolve) => fixture.http.close(resolve))
    await page.getByRole('button', { name: 'Save project', exact: true }).click()
    await page.getByText('Cannot connect to the local BuildX API. Start the API server and try again.').waitFor()
    assert.equal(await page.locator('#project-problem').inputValue(), 'An offline draft to preserve.')
    fixture.http.listen(port, '127.0.0.1')
    await new Promise((resolve) => fixture.http.once('listening', resolve))
    await page.getByRole('button', { name: 'Retry', exact: true }).click()
    await page.getByText('Saved to cloud', { exact: true }).waitFor()
    const ada = await fixture.call('/auth/login', { method: 'POST', body: { email: 'ada@example.com', password: 'x' } })
    const project = (await fixture.call(`/projects/${legacy.id}`, { token: ada.token })).project
    await fixture.call(`/projects/${legacy.id}/title`, { method: 'PATCH', token: ada.token, body: { title: 'Changed elsewhere', version: project.version } })
    await page.locator('#project-problem').fill('Unsaved conflicting draft')
    await page.getByRole('button', { name: 'Save project', exact: true }).click()
    await page.getByRole('button', { name: 'Reload saved copy' }).waitFor()
    assert.equal(await page.locator('#project-problem').inputValue(), 'Unsaved conflicting draft')
    await page.getByRole('button', { name: 'Reload saved copy' }).click()
    await page.getByRole('dialog', { name: 'Discard unsaved changes?' }).waitFor()
    await page.getByRole('button', { name: 'Cancel', exact: true }).click()
    assert.equal(await page.locator('#project-problem').inputValue(), 'Unsaved conflicting draft')
    await page.getByRole('button', { name: 'Reload saved copy' }).click()
    await page.getByRole('button', { name: 'Discard changes', exact: true }).click()
    await page.getByRole('button', { name: 'Open Changed elsewhere' }).waitFor()
    assert.equal(await page.locator('#project-problem').inputValue(), 'An offline draft to preserve.')
    await page.locator('#project-problem').fill('Draft retained through session expiry')
    await fixture.db.collection('sessions').deleteMany({ userId: ada.user.id })
    await page.getByRole('button', { name: 'Save project', exact: true }).click()
    await page.getByRole('heading', { name: 'Welcome back.' }).waitFor()
    assert.equal(await page.locator('#auth-email').getAttribute('readonly'), '')
    // The locked workspace must not keep issuing requests after expiry.
    await page.keyboard.press('Meta+s')
    await page.locator('#auth-password').fill('x')
    await page.locator('button[type="submit"]').last().click()
    await page.getByRole('button', { name: 'Save project', exact: true }).waitFor()
    assert.equal(await page.locator('#project-problem').inputValue(), 'Draft retained through session expiry')
    await page.getByRole('button', { name: 'Log out', exact: true }).click()
    await page.getByRole('dialog', { name: 'Discard unsaved changes?' }).waitFor()
    await page.getByRole('button', { name: 'Cancel', exact: true }).click()
    await page.getByRole('button', { name: 'Save project', exact: true }).click()
    await page.getByText('Saved to cloud', { exact: true }).waitFor()
    const encryptionAvailable = await app.evaluate(({ safeStorage }) => safeStorage.isEncryptionAvailable())
    if (encryptionAvailable) {
      const encrypted = await fs.readFile(path.join(directory, 'auth-session.enc'))
      assert.equal(encrypted.includes(Buffer.from('ada@example.com')), false)
      assert.equal(encrypted.includes(Buffer.from('token')), false)
    }
    await app.close()
    page = await launch()
    if (!encryptionAvailable) { await page.locator('#auth-email').waitFor(); await signin(page, 'ada@example.com') }
    await page.getByRole('heading', { name: 'Start with a clear plan.' }).waitFor()
    await page.getByRole('button', { name: 'Open Changed elsewhere' }).click()
    assert.equal(await page.locator('#project-problem').inputValue(), 'Draft retained through session expiry')
    await page.getByRole('button', { name: 'Log out', exact: true }).click()
    await page.getByRole('heading', { name: 'Welcome to BuildX.' }).waitFor()
    await signin(page, fixture.account.email, PASSWORD)
    await page.getByRole('heading', { name: 'Start with a clear plan.' }).waitFor()
    assert.equal(await page.getByRole('button', { name: 'Open Changed elsewhere' }).count(), 0)
    assert.equal((await page.evaluate((id) => window.buildx.exports.pdf(id), legacy.id)).code, 'NOT_FOUND')
    const denied = await page.evaluate((id) => window.buildx.generation.generate(id, 1), legacy.id)
    assert.equal(denied.code, 'NOT_FOUND')
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(720, 560))
    await page.getByRole('button', { name: 'Log out', exact: true }).click()
    await page.locator('#auth-email').waitFor()
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await page.locator('#auth-email').focus()
    await page.keyboard.press('Tab')
    assert.equal(await page.locator('#auth-password').evaluate((node) => node === document.activeElement), true)
    const bounds = await page.locator('.auth-form-wrap').boundingBox()
    assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= 721)
    if (process.env.BUILDX_SCREENSHOT_DIR) await page.screenshot({ path: path.join(process.env.BUILDX_SCREENSHOT_DIR, 'buildx-login-compact.png') })
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(680, 520))
    await page.getByRole('button', { name: 'Sign up', exact: true }).click()
    await page.getByRole('button', { name: 'Create account', exact: true }).click()
    await page.getByRole('button', { name: 'Create account', exact: true }).scrollIntoViewIfNeeded()
    const submitBox = await page.getByRole('button', { name: 'Create account', exact: true }).boundingBox()
    assert.ok(submitBox.y >= 0 && submitBox.y + submitBox.height <= 521)
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    if (process.env.BUILDX_SCREENSHOT_DIR) await page.screenshot({ path: path.join(process.env.BUILDX_SCREENSHOT_DIR, 'buildx-signup-minimum.png') })
    assert.deepEqual(pageErrors, [])
    console.log('Auth desktop test passed: signup/login, validation, secure restoration, automatic project migration, offline retry, conflicts, expired-session drafts, account isolation, logout, keyboard, resize.')
  } finally {
    if (app) await app.close().catch(() => {})
    await fixture.close()
    await fs.rm(directory, { recursive: true, force: true })
  }
}
main().catch((error) => { console.error(error); process.exitCode = 1 })
